Email Email::parse(std::string_view input) {
        try {
            auto text=account_text::lower(account_text::trim(account_text::decode(input)));
            const auto at=text.find(U'@');
            if(text.size()>kMaxEmailLength || at==std::u32string::npos || at==0 || at>kMaxEmailLocalLength ||
               text.find(U'@',at+1)!=std::u32string::npos || at+1>=text.size())throw std::invalid_argument("email");
            const auto domain=text.substr(at+1);
            if(domain.find(U'.')==std::u32string::npos || domain.front()==U'.'||domain.back()==U'.'||domain.find(U"..")!=std::u32string::npos)
                throw std::invalid_argument("email");
            for(char32_t c:text)if(account_text::space(c)||account_text::control(c))throw std::invalid_argument("email");
            return Email(account_text::encode(text));
        } catch(const std::invalid_argument &) {
            throw AccountValidationException("InvalidEmail","Email không hợp lệ");
        }
    }

std::string Email::masked() const {
        const auto text=account_text::decode(value_);
        return account_text::encode(std::u32string(1,text.front()))+"***"+value_.substr(value_.find('@'));
    }

