std::u32string decode(std::string_view text) {
    std::u32string result;
    for (size_t i=0; i<text.size();) {
        const auto first=static_cast<unsigned char>(text[i++]);
        char32_t value=first; unsigned count=0;
        if(first>=0xc2 && first<=0xdf) {value=first&0x1f;count=1;}
        else if(first>=0xe0 && first<=0xef) {value=first&0x0f;count=2;}
        else if(first>=0xf0 && first<=0xf4) {value=first&0x07;count=3;}
        else if(first>=0x80) throw std::invalid_argument("Invalid UTF-8");
        for(unsigned n=0;n<count;++n) {
            if(i>=text.size())throw std::invalid_argument("Invalid UTF-8");
            const auto next=static_cast<unsigned char>(text[i++]);
            if((next&0xc0)!=0x80)throw std::invalid_argument("Invalid UTF-8");
            value=(value<<6)|(next&0x3f);
        }
        if((count==1 && value<0x80)||(count==2 && value<0x800)||
           (count==3 && value<0x10000)||value>0x10ffff||(value>=0xd800 && value<=0xdfff))
            throw std::invalid_argument("Invalid UTF-8");
        result.push_back(value);
    }
    return result;
}
std::string encode(std::u32string_view text) {
    std::string result;
    for(char32_t c:text) {
        if(c<0x80)result.push_back(static_cast<char>(c));
        else if(c<0x800) {result.push_back(static_cast<char>(0xc0|(c>>6)));result.push_back(static_cast<char>(0x80|(c&0x3f)));}
        else if(c<0x10000) {result.push_back(static_cast<char>(0xe0|(c>>12)));result.push_back(static_cast<char>(0x80|((c>>6)&0x3f)));result.push_back(static_cast<char>(0x80|(c&0x3f)));}
        else {result.push_back(static_cast<char>(0xf0|(c>>18)));result.push_back(static_cast<char>(0x80|((c>>12)&0x3f)));result.push_back(static_cast<char>(0x80|((c>>6)&0x3f)));result.push_back(static_cast<char>(0x80|(c&0x3f)));}
    }
    return result;
}
bool space(char32_t c) {
    return (c>=9 && c<=13)||c==32||c==0x85||c==0xa0||c==0x1680||
           (c>=0x2000 && c<=0x200a)||c==0x2028||c==0x2029||c==0x202f||c==0x205f||c==0x3000;
}
std::u32string trim(std::u32string text) {
    const auto first=std::find_if_not(text.begin(),text.end(),space);
    const auto last=std::find_if_not(text.rbegin(),text.rend(),space).base();
    return first<last?std::u32string(first,last):std::u32string{};
}
